#!/usr/bin/env python3
"""
merge-ffm-bindings.py

Merges FFM bindings generated by jextract from multiple platforms into a unified
artifact structure with platform-specific feature variants.

Usage:
    python3 merge-ffm-bindings.py <output_dir> <linux_plain> <linux_ros3> \
                                   <windows_plain> <windows_ros3> \
                                   <macos_plain> <macos_ros3>

Arguments:
    output_dir      - Directory where merged bindings will be placed
    linux_plain     - Linux jextract output (plain variant)
    linux_ros3      - Linux jextract output (ros3 variant)
    windows_plain   - Windows jextract output (plain variant)
    windows_ros3    - Windows jextract output (ros3 variant)
    macos_plain     - macOS jextract output (plain variant)
    macos_ros3      - macOS jextract output (ros3 variant)

Output structure:
    output_dir/
    ├── features/
    │   ├── plain/
    │   │   ├── linux/      # Linux plain variant hdf5_h*.java
    │   │   ├── macos/      # macOS plain variant hdf5_h*.java
    │   │   └── windows/    # Windows plain variant hdf5_h*.java
    │   └── ros3/
    │       ├── linux/      # Linux ROS3 variant hdf5_h*.java + H5FD_ros3*
    │       ├── macos/      # macOS ROS3 variant hdf5_h*.java + H5FD_ros3*
    │       └── windows/    # Windows ROS3 variant hdf5_h*.java + H5FD_ros3*
    └── org/
        ├── linux/          # Linux platform-specific types
        ├── macos/          # macOS platform-specific types
        └── windows/        # Windows platform-specific types
"""

import os
import sys
import shutil
import hashlib
import argparse
from pathlib import Path
from typing import Dict, List, Set, Tuple


def compute_file_hash(file_path: Path) -> str:
    """Compute SHA256 hash of a file."""
    sha256 = hashlib.sha256()
    with open(file_path, 'rb') as f:
        for chunk in iter(lambda: f.read(8192), b''):
            sha256.update(chunk)
    return sha256.hexdigest()


def compare_files(file1: Path, file2: Path) -> bool:
    """Compare two files for equality."""
    if not file1.exists() or not file2.exists():
        return False
    return compute_file_hash(file1) == compute_file_hash(file2)


def get_java_files(directory: Path) -> Set[str]:
    """Get all Java files in a directory recursively, returning relative paths."""
    if not directory.exists():
        return set()

    java_files = set()
    for root, _, files in os.walk(directory):
        for file in files:
            if file.endswith('.java'):
                full_path = Path(root) / file
                rel_path = full_path.relative_to(directory)
                java_files.add(str(rel_path))
    return java_files


def validate_platform_independent_code(platforms: Dict[str, Path], variant: str) -> Tuple[bool, List[str]]:
    """
    Validate that org/hdfgroup/javahdf5/ code is identical across platforms.

    Returns:
        (is_valid, error_messages)
    """
    errors = []

    # Get all Java files from the platform-independent directory
    org_files = {}
    for platform_name, platform_dir in platforms.items():
        org_dir = platform_dir / "org" / "hdfgroup" / "javahdf5"
        if org_dir.exists():
            files = get_java_files(org_dir)
            org_files[platform_name] = files
        else:
            errors.append(f"⚠️  {platform_name} ({variant}): org/hdfgroup/javahdf5 directory not found")

    if not org_files:
        errors.append(f"❌ {variant}: No platform-independent code found in any platform")
        return False, errors

    # Get union of all files
    all_files = set()
    for files in org_files.values():
        all_files.update(files)

    print(f"\n📁 Validating {len(all_files)} platform-independent files ({variant} variant)...")

    # Check each file exists in all platforms and is identical
    for rel_file in sorted(all_files):
        file_hashes = {}
        for platform_name, platform_dir in platforms.items():
            file_path = platform_dir / "org" / "hdfgroup" / "javahdf5" / rel_file
            if file_path.exists():
                file_hashes[platform_name] = compute_file_hash(file_path)
            else:
                errors.append(f"⚠️  {rel_file}: Missing in {platform_name} ({variant})")

        # Check all hashes are identical
        if len(set(file_hashes.values())) > 1:
            errors.append(f"❌ {rel_file}: Platform differences detected ({variant})")
            for platform, hash_val in file_hashes.items():
                errors.append(f"     {platform}: {hash_val[:12]}...")
        elif file_hashes:
            print(f"  ✓ {rel_file}")

    is_valid = len(errors) == 0
    return is_valid, errors


def copy_platform_independent_code(source_dir: Path, output_dir: Path):
    """Copy platform-independent code to output directory."""
    src_org = source_dir / "org"
    dst_org = output_dir / "org"

    if src_org.exists():
        if dst_org.exists():
            shutil.rmtree(dst_org)
        shutil.copytree(src_org, dst_org)
        print(f"  ✓ Copied org/hdfgroup/javahdf5/ from {source_dir.name}")


def extract_feature_files(source_dir: Path) -> List[str]:
    """
    Extract hdf5_h*.java files from jextract output.
    These are the platform-specific feature files.
    """
    feature_files = []
    org_dir = source_dir / "org" / "hdfgroup" / "javahdf5"

    if not org_dir.exists():
        return feature_files

    for file in org_dir.glob("hdf5_h*.java"):
        feature_files.append(file.name)

    # Also check for ROS3-specific files
    for file in org_dir.glob("H5FD_ros3*.java"):
        feature_files.append(file.name)

    return feature_files


def copy_feature_files(source_dir: Path, output_feature_dir: Path, files: List[str]):
    """Copy feature files to the appropriate features/ subdirectory."""
    src_org = source_dir / "org" / "hdfgroup" / "javahdf5"
    output_feature_dir.mkdir(parents=True, exist_ok=True)

    for file_name in files:
        src_file = src_org / file_name
        dst_file = output_feature_dir / file_name
        if src_file.exists():
            shutil.copy2(src_file, dst_file)
            print(f"    ✓ {file_name}")


def merge_bindings(output_dir: Path, platforms: Dict[str, Dict[str, Path]]) -> bool:
    """
    Merge bindings from all platforms into unified structure.

    Args:
        output_dir: Output directory for merged bindings
        platforms: Dict of variant -> Dict of platform -> jextract output dir

    Returns:
        True if merge successful, False otherwise
    """
    print("\n" + "="*60)
    print("MERGING FFM BINDINGS")
    print("="*60)

    # Process each variant (plain, ros3)
    for variant, platform_dirs in platforms.items():
        print(f"\n{'='*60}")
        print(f"Processing {variant.upper()} variant")
        print(f"{'='*60}")

        # Note: Platform validation is skipped because jextract generates
        # platform-specific types (FILE, pthread_*, callbacks, etc.).
        # This is expected and correct behavior.
        print(f"\n⚠️  Skipping platform validation - platform-specific types are expected")
        print(f"   (FILE, pthread_*, callbacks contain platform-specific code)")

        # Copy org/ directory per-platform since types differ across platforms
        if variant == "plain":  # Only copy org/ from plain variant
            for platform_name, platform_dir in platform_dirs.items():
                if platform_dir:
                    src_org = platform_dir / "org"
                    if platform_name == "linux":
                        # Linux org/ → org/linux/
                        dst_org = output_dir / "org" / "linux"
                    elif platform_name == "windows":
                        # Windows org/ → org/windows/
                        dst_org = output_dir / "org" / "windows"
                    elif platform_name == "macos":
                        # macOS org/ → org/macos/
                        dst_org = output_dir / "org" / "macos"

                    if src_org.exists():
                        if dst_org.exists():
                            shutil.rmtree(dst_org)
                        shutil.copytree(src_org, dst_org)
                        print(f"  ✓ Copied org/ from {platform_name} to org/{platform_name}/")

        # Extract and copy feature files (platform-specific per variant)
        print(f"\n📦 Extracting feature files ({variant})...")

        # Each platform gets its own feature directory under variant
        for platform_name, platform_dir in platform_dirs.items():
            if platform_dir and platform_dir.exists():
                feature_files = extract_feature_files(platform_dir)

                # features/{variant}/{platform}/
                variant_platform_dir = output_dir / "features" / variant / platform_name

                print(f"\n  📂 features/{variant}/{platform_name}/:")
                copy_feature_files(platform_dir, variant_platform_dir, feature_files)

    # Always return True since platform-specific differences are expected
    return True


def generate_validation_report(output_dir: Path, platforms: Dict[str, Dict[str, Path]]):
    """Generate a validation report."""
    report_path = output_dir / "VALIDATION_REPORT.md"

    with open(report_path, 'w') as f:
        f.write("# FFM Bindings Validation Report\n\n")
        f.write("**Generated:** " + str(Path.cwd()) + "\n\n")
        f.write("---\n\n")

        f.write("## Platforms Processed\n\n")
        for variant, platform_dirs in platforms.items():
            f.write(f"### {variant.upper()} Variant\n\n")
            for platform, path in platform_dirs.items():
                f.write(f"- **{platform}**: `{path}`\n")
            f.write("\n")

        f.write("## Validation Summary\n\n")

        for variant, platform_dirs in platforms.items():
            f.write(f"### {variant.upper()} Variant\n\n")
            is_valid, errors = validate_platform_independent_code(platform_dirs, variant)

            if is_valid:
                f.write(f"✅ **PASSED** - All platform-independent files are identical\n\n")
            else:
                f.write(f"❌ **FAILED** - Platform differences detected:\n\n")
                for error in errors:
                    f.write(f"- {error}\n")
                f.write("\n")

        f.write("## Output Structure\n\n")
        f.write("```\n")
        f.write("output/\n")
        f.write("├── features/\n")
        f.write("│   ├── plain/\n")
        f.write("│   │   ├── linux/      # Linux plain hdf5_h*.java\n")
        f.write("│   │   ├── macos/      # macOS plain hdf5_h*.java\n")
        f.write("│   │   └── windows/    # Windows plain hdf5_h*.java\n")
        f.write("│   └── ros3/\n")
        f.write("│       ├── linux/      # Linux ROS3 hdf5_h*.java + H5FD_ros3*\n")
        f.write("│       ├── macos/      # macOS ROS3 hdf5_h*.java + H5FD_ros3*\n")
        f.write("│       └── windows/    # Windows ROS3 hdf5_h*.java + H5FD_ros3*\n")
        f.write("└── org/\n")
        f.write("    ├── linux/          # Linux platform-specific types\n")
        f.write("    ├── macos/          # macOS platform-specific types\n")
        f.write("    └── windows/        # Windows platform-specific types\n")
        f.write("```\n\n")
        f.write("**Note:** Both features/ and org/ are platform-specific because jextract\n")
        f.write("generates platform-specific code for hdf5_h*.java wrapper files, FILE, pthread_*,\n")
        f.write("and callback types. Each variant (plain/ros3) has platform-specific feature files.\n\n")

        # Count files
        total_files = 0
        for root, _, files in os.walk(output_dir):
            total_files += sum(1 for f in files if f.endswith('.java'))

        f.write(f"**Total Java files:** {total_files}\n\n")

    print(f"\n📄 Validation report: {report_path}")


def main():
    parser = argparse.ArgumentParser(
        description="Merge FFM bindings from multiple platforms"
    )
    parser.add_argument("output_dir", help="Output directory for merged bindings")
    parser.add_argument("linux_plain", help="Linux jextract output (plain)")
    parser.add_argument("linux_ros3", help="Linux jextract output (ros3)")
    parser.add_argument("windows_plain", help="Windows jextract output (plain)")
    parser.add_argument("windows_ros3", help="Windows jextract output (ros3)")
    parser.add_argument("macos_plain", help="macOS jextract output (plain)")
    parser.add_argument("macos_ros3", help="macOS jextract output (ros3)")

    args = parser.parse_args()

    output_dir = Path(args.output_dir)

    # Organize inputs
    platforms = {
        "plain": {
            "linux": Path(args.linux_plain),
            "windows": Path(args.windows_plain),
            "macos": Path(args.macos_plain),
        },
        "ros3": {
            "linux": Path(args.linux_ros3),
            "windows": Path(args.windows_ros3),
            "macos": Path(args.macos_ros3),
        }
    }

    # Validate all input directories exist
    print("\n🔍 Validating input directories...")
    all_exist = True
    for variant, platform_dirs in platforms.items():
        for platform, path in platform_dirs.items():
            if not path.exists():
                print(f"❌ Not found: {platform} ({variant}): {path}")
                all_exist = False
            else:
                print(f"✓ Found: {platform} ({variant}): {path}")

    if not all_exist:
        print("\n❌ Some input directories not found. Aborting.")
        return 1

    # Create output directory
    output_dir.mkdir(parents=True, exist_ok=True)

    # Merge bindings
    success = merge_bindings(output_dir, platforms)

    # Generate validation report
    generate_validation_report(output_dir, platforms)

    if success:
        print("\n" + "="*60)
        print("✅ MERGE COMPLETED SUCCESSFULLY")
        print("="*60)
        print(f"\nOutput directory: {output_dir.absolute()}")
        return 0
    else:
        print("\n" + "="*60)
        print("❌ MERGE COMPLETED WITH ERRORS")
        print("="*60)
        print("\nPlease review the validation report for details.")
        return 1


if __name__ == "__main__":
    sys.exit(main())
